/* Keys that are DELIBERATELY English-only in both languages — contract
   clause form/ref/title/entitlement/evidence text is never routed
   through this dictionary at all (it comes straight from js/clauses.js
   and is rendered verbatim), so there is nothing to list here for that;
   this list is for keys that legitimately exist only in I18N_EN because
   the English wording is also correct/used as-is in the zh interface
   (e.g. the two instructionType values, which are contract-vocabulary
   proper terms kept bilingual with a Chinese gloss already inline —
   see instructionType.* above, which DO have zh entries). Currently
   empty: every I18N_EN key has a matching I18N_ZH key. Kept as a real,
   tested list so a future addition that is deliberately English-only
   has a documented place to go instead of silently falling back. */
var I18N_EN_ONLY_KEYS = [];

var I18N_DICTS = { en: I18N_EN, zh: I18N_ZH };

/* -----------------------------------------------------------
   Core API
----------------------------------------------------------- */

function getLang() {
    if (typeof localStorage === "undefined") return "en";
    try {
        var v = localStorage.getItem(LANG_KEY);
        return v === "zh" ? "zh" : "en";
    } catch (e) {
        return "en";
    }
}

function setLang(lang) {
    var l = lang === "zh" ? "zh" : "en";
    if (typeof localStorage !== "undefined") {
        try { localStorage.setItem(LANG_KEY, l); } catch (e) { /* ignore */ }
    }
    return l;
}

/* t(key, params) — current language, falling back to English when the
   key is missing in the current language's dictionary, and to the raw
   key only if it is missing from English too (should not happen for a
   complete dictionary; see test/i18n.test.js's completeness check). */
function t(key, params) {
    var lang = getLang();
    var dict = I18N_DICTS[lang] || I18N_EN;
    var str = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key]
        : Object.prototype.hasOwnProperty.call(I18N_EN, key) ? I18N_EN[key]
        : key;

    if (params) {
        Object.keys(params).forEach(function (k) {
            var value = params[k];
            str = str.split("{" + k + "}").join(value === null || value === undefined ? "" : String(value));
        });
    }
    return str;
}

/* Locale-appropriate list join: "A, B and C" in English, "A、B、C" in
   Chinese (no trailing conjunction — that is standard Chinese list
   style, not a missing translation). */
function joinList(items) {
    var list = (items || []).filter(function (s) { return s !== null && s !== undefined && s !== ""; });
    if (list.length === 0) return "";
    if (list.length === 1) return list[0];
    if (getLang() === "zh") return list.join("、");
    return list.slice(0, -1).join(", ") + " and " + list[list.length - 1];
}

/* -----------------------------------------------------------
   Browser-only: static-HTML translation + the language switch widget
----------------------------------------------------------- */

/* Applies t() to every element carrying a data-i18n* attribute under
   `root` (default: the whole document). Static chrome that is never
   re-rendered by a page-*.js script (headings, table header cells,
   button labels, placeholders defined directly in the HTML) is marked
   up this way instead of being duplicated into JS template strings. */
function applyI18n(root) {
    if (typeof document === "undefined") return;
    var scope = root || document;

    scope.querySelectorAll("[data-i18n]").forEach(function (el) {
        el.textContent = t(el.getAttribute("data-i18n"));
    });
    scope.querySelectorAll("[data-i18n-html]").forEach(function (el) {
        el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
        el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach(function (el) {
        el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
    });
}

function renderLangSwitch() {
    var lang = getLang();
    return '<div class="lang-switch" id="langSwitch" role="group" aria-label="' +
        t("lang.switchTo") + '">' +
        '<button type="button" class="lang-btn' + (lang === "en" ? " active" : "") +
            '" data-lang="en">EN</button>' +
        '<button type="button" class="lang-btn' + (lang === "zh" ? " active" : "") +
            '" data-lang="zh">中文</button>' +
        "</div>";
}

/* A full reload is the deliberate, simple way to "re-render the current
   page in the chosen language" — every page-*.js render function reads
   getLang() live via t(), so a fresh load is enough and avoids having
   to re-run every panel's render function by hand from here. */
function wireLangSwitch(container) {
    if (!container) return;
    container.querySelectorAll(".lang-btn").forEach(function (btn) {
        btn.addEventListener("click", function () {
            var chosen = btn.getAttribute("data-lang");
            if (chosen === getLang()) return;
            setLang(chosen);
            window.location.reload();
        });
    });
}

if (typeof module !== "undefined" && module.exports) {
    module.exports = {
        LANGS, I18N_EN, I18N_ZH, I18N_EN_ONLY_KEYS,
        getLang, setLang, t, joinList,
        applyI18n, renderLangSwitch, wireLangSwitch
    };
}
